export function pickPhrase(lang: Lang, correct: boolean): string {
  const keys = correct ? ["win0", "win1", "win2", "win3", "win4"] : ["lose0", "lose1", "lose2", "lose3"];
  const i = Math.floor(Math.random() * keys.length);
  return t(lang, keys[i]! as TKey);
}
